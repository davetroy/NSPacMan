def rowbits(row, pred):
    bits=0
    for x,ch in enumerate(row):
        if pred(ch): bits |= 1 << (31-x)
    return [(bits>>24)&0xff,(bits>>16)&0xff,(bits>>8)&0xff,bits&0xff]

walls=[]; dots=[]; pills=[]; doors=[]
ndots=0
for y,row in enumerate(MAZE):
    walls.append(rowbits(row, lambda c: c=='#'))
    dots.append(rowbits(row, lambda c: c=='.'))
    ndots += row.count('.')
    for x,ch in enumerate(row):
        if ch=='o': pills.append((x,y))
        if ch=='D': doors.append((x,y))
assert len(pills)==4, pills

# sprites: 8x8, '#' = pixel. MSB = leftmost.
def spr(rows):
    out=[]
    for r in rows:
        b=0
        for i,ch in enumerate(r):
            if ch=='#': b |= 1<<(7-i)
        out.append(b)
    return out

