    w("wallrows:\n")
    for r in walls: w("        db "+",".join(f"0{b:02x}h" for b in r)+"\n")
    w("dotrows:\n")
    for r in dots: w("        db "+",".join(f"0{b:02x}h" for b in r)+"\n")
